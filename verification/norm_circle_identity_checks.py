#!/usr/bin/env python3
"""Small numerical identity checks for the norm-tail proof.

These floating-point checks detect phase, normalization, and quotient-index
mistakes. They are independent of the Arb numerical certificate and are not
proofs of the general identities.

Only the Python standard library is required. Run:
    python verification/norm_circle_identity_checks.py
"""

from __future__ import annotations

import cmath
import math


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ArithmeticError(message)


def complex_sum(values) -> complex:
    values = tuple(values)
    return complex(
        math.fsum(z.real for z in values),
        math.fsum(z.imag for z in values),
    )


def gauss_expansions() -> None:
    """Check both periodic and antiperiodic quadratic phases, including b=1."""
    worst_phase = 0.0
    worst_magnitude = 0.0
    cases = 0
    for b in range(1, 33):
        for a in range(2 * b):
            if math.gcd(a, b) != 1:
                continue
            eta = 0.5 if (a * b) % 2 else 0.0
            coefficients = [
                complex_sum(
                    cmath.exp(1j * math.pi * a * r * r / b)
                    * cmath.exp(-2j * math.pi * (ell + eta) * r / b)
                    for r in range(b)
                ) / b
                for ell in range(b)
            ]
            worst_magnitude = max(
                worst_magnitude,
                max(abs(abs(c) - 1 / math.sqrt(b)) for c in coefficients),
            )
            for x in range(-2 * b, 2 * b + 1):
                reconstructed = complex_sum(
                    coefficients[ell]
                    * cmath.exp(2j * math.pi * (ell + eta) * x / b)
                    for ell in range(b)
                )
                exact = cmath.exp(1j * math.pi * a * x * x / b)
                worst_phase = max(worst_phase, abs(reconstructed - exact))
            cases += 1
    require(worst_phase < 2e-11, "quadratic-phase reconstruction failed")
    require(worst_magnitude < 2e-12, "Gauss coefficient magnitude failed")
    print("PASS twisted_gauss_expansions", "cases", cases)
    print("  maximum_phase_error", format(worst_phase, ".6e"))
    print("  maximum_magnitude_error", format(worst_magnitude, ".6e"))


def gaussian_1d(coefficient: float, shift: float, scale: float = 1.0) -> float:
    return math.fsum(
        math.exp(-coefficient * (x * scale + shift) ** 2)
        for x in range(-40, 41)
    )


def merger_sums(b: int, eta: float, coefficient: float) -> tuple[float, float]:
    # Lambda* / Z^2 is generated by (1,4)/17.
    representatives = [(a / 17, ((4 * a) % 17) / 17) for a in range(17)]
    left = math.fsum(
        gaussian_1d(coefficient, eta / b - w1, 1 / b)
        * gaussian_1d(coefficient, eta / b - w2, 1 / b)
        for w1, w2 in representatives
    )
    right = math.fsum(
        gaussian_1d(coefficient / b**2, w1 + eta)
        * gaussian_1d(coefficient / b**2, w2 + eta)
        for w1, w2 in representatives
    )
    return left, right


def merger_checks() -> None:
    """Check the coprime merger and exhibit the noncoprime boundary."""
    worst_relative = 0.0
    for b in (1, 2, 3, 4, 5, 7):
        for eta in (0.0, 0.5):
            left, right = merger_sums(b, eta, 7.0)
            worst_relative = max(
                worst_relative, abs(left - right) / max(1.0, abs(right))
            )
    require(worst_relative < 1e-12, "coprime quotient merger failed")

    # For b=17 multiplication by b kills this quotient. The general formula
    # has a kernel factor 17 and image lattice Z^2, not the full dual.
    b = 17
    coefficient = 7.0 * b**2
    left, incorrect_coprime_rhs = merger_sums(b, 0.0, coefficient)
    corrected_rhs = 17 * gaussian_1d(7.0, 0.0) ** 2
    require(abs(left - corrected_rhs) < 1e-10, "kernel-factor identity failed")
    require(
        abs(left - incorrect_coprime_rhs) > 1,
        "noncoprime example did not distinguish the two formulas",
    )
    print("PASS finite_quotient_merger")
    print("  maximum_coprime_relative_error", format(worst_relative, ".6e"))
    print("  noncoprime_naive_formula_gap", format(abs(left - incorrect_coprime_rhs), ".6e"))


def contour_check() -> None:
    """Compare the contour to a direct finite sum on an odd-index quotient."""
    alpha = 0.025
    K = 60
    beta = 1 / K
    t = alpha - beta
    w = (1 / 17, 4 / 17)
    cutoff = 60
    count = 16384
    integers = range(-cutoff, cutoff + 1)
    normalization = math.fsum(math.exp(-alpha * x * x) for x in integers)
    direct = math.fsum(
        math.exp(-alpha * (x * x + y * y))
        * math.cos(2 * math.pi * (w[0] * x + w[1] * y))
        for x in integers
        for y in integers
        if x * x + y * y >= K
    ) / normalization**2

    # Symmetric positive and negative x combine into real cosine weights.
    squares = [x * x for x in range(1, cutoff + 1)]
    weights = [
        [
            2 * math.exp(-beta * x * x) * math.cos(2 * math.pi * coordinate * x)
            for x in range(1, cutoff + 1)
        ]
        for coordinate in w
    ]
    integrands = []
    for k in range(count):
        angle = 2 * math.pi * k / count
        phases = [cmath.exp(1j * angle * square) for square in squares]
        theta1 = 1 + complex_sum(c * phase for c, phase in zip(weights[0], phases))
        theta2 = 1 + complex_sum(c * phase for c, phase in zip(weights[1], phases))
        integrands.append(
            theta1 * theta2 * cmath.exp(-1j * K * angle)
            / (1 - cmath.exp(-t - 1j * angle))
        )
    contour = (
        math.exp(-t * K)
        / normalization**2
        * complex_sum(integrands)
        / count
    )
    error = abs(contour - direct)
    require(error < 1e-12, "geometric upper-tail contour failed")
    print("PASS upper_tail_contour")
    print("  direct_finite_sum", format(direct, ".16e"))
    print("  contour_real_part", format(contour.real, ".16e"))
    print("  absolute_difference", format(error, ".6e"))


def main() -> None:
    gauss_expansions()
    merger_checks()
    contour_check()
    print("IDENTITY_CHECKS_PASSED (floating-point checks, not the Arb certificate)")


if __name__ == "__main__":
    main()
